function sum(a, b) {
  return a + b;
}

function sub(a, b) {
  return a - b;
}

function mult(a, b) {
  return a * b;
}

function div(a, b) {
  return a / b;
}

function pow(a, b) {
  return a ** b;
}

function root(a, b) {
  return a ** (1/b);
}

export {
    sum,
    sub,
    mult,
    div,
    pow,
    root
};
